"""Агент-исполнитель демо-стенда: детерминированная выработка артефакта.

Честно о природе: в изолированном контуре без подключённой LLM артефакт
формируется **детерминированным rule-based агентом** (шаблон по виду задачи +
контракт). Это тот самый fallback из ТЗ — «rule-based для гарантированной
демонстрации без интернета».

Если LLM доступна (например, локальная Ollama в сети контура), тот же контракт
можно отдать ей — точка подключения одна: `LIN` в `demo/engine/worker.py`.
Никакого Excel и прикладной аналитики здесь нет: агент вырабатывает результат
по контракту задачи, а не парсит таблицы.
"""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any


def _checks_block(contract: dict[str, Any]) -> str:
    checks = contract.get("checks") or []
    if not checks:
        return "_проверок контрактом не задано_"
    lines = []
    for c in checks:
        cid = c.get("id") or f"{c.get('type')}/{c.get('run', '')}"
        lines.append(f"- `{cid}` — тип `{c.get('type')}` (run: `{c.get('run', '')}`)")
    return "\n".join(lines)


def artifact_for(contract: dict[str, Any]) -> str:
    """Сформировать артефакт задачи по её контракту (вид задачи решает форму)."""
    kind = (contract.get("kind") or "task").strip()
    desc = (contract.get("description") or "").strip()
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    header = (
        f"# Артефакт задачи\n\n"
        f"**Вид:** `{kind}`  \n"
        f"**Постановка:** {desc or '—'}  \n"
        f"**Выработан:** {ts}\n\n"
    )

    if kind == "analysis":
        body = (
            "## Анализ и план работ\n\n"
            "1. **Контекст.** Выделены вход и ожидаемый результат постановки.\n"
            "2. **Декомпозиция.** Работа разбита на измеримые шаги с критериями приёмки.\n"
            "3. **Риски.** Обозначены зависимости от последующих стадий конвейера.\n"
            "4. **Готовность.** План передан на стадию исполнения.\n\n"
            f"**Критерии приёмки:**\n{_checks_block(contract)}\n"
        )
    elif kind == "execution":
        body = (
            "## Результат исполнения\n\n"
            "```\n"
            "// Результат основной работы по задаче\n"
            "// (артефакт выработан агентом-исполнителем в контуре)\n"
            "```\n\n"
            "Основной результат подготовлен и передан на проверку и аудит.\n\n"
            f"**Критерии приёмки:**\n{_checks_block(contract)}\n"
        )
    elif kind == "review":
        body = (
            "## Проверка и аудит\n\n"
            "- Результат предыдущей стадии проверен по контракту.\n"
            "- Наблюдённые проверки подтверждены (см. запись ревью в движке).\n"
            "- Замечаний, блокирующих приёмку, не выявлено.\n\n"
            f"**Критерии приёмки:**\n{_checks_block(contract)}\n"
        )
    else:
        body = (
            "## Результат\n\n"
            f"Задача вида `{kind}` выполнена агентом-исполнителем в контуре.\n\n"
            f"**Критерии приёмки:**\n{_checks_block(contract)}\n"
        )

    footer = (
        "\n---\n"
        "_Артефакт выработан агентом-исполнителем демо-контура (rule-based режим); "
        "координация задачи выполнена движком swarm-dispatcher._\n"
    )
    return header + body + footer
